<?php
require_once __DIR__.'/../includes/requisitions-data.php';
require_once __DIR__.'/../design-system/requisitions-samples.php';
$checks=0;
function check($condition,string $message): void { global $checks; if (!$condition) throw new RuntimeException($message); $checks++; }
$pdo=cssrRequisitionSamples();
$all=cssrRequisitions($pdo,[],true,0);
check($all['total']===18 && count($all['rows'])===10 && $all['pages']===2,'Paginated list');
check($all['counts']['For Approval']===7,'Pending maps to For Approval');
check($all['counts']['Approved']===4 && $all['counts']['For Release']===3,'Approved includes ready requests');
check($all['counts']['Rejected']===2,'Rejected is distinct from Cancelled');
check(cssrRequisitions($pdo,['page'=>999],true,0)['page']===2,'Clamp page');
check(cssrRequisitions($pdo,['q'=>'0099'],true,0)['total']===1,'TRN search');
check(cssrRequisitions($pdo,['q'=>"' OR 1=1 --"],true,0)['total']===0,'Parameterized search');
check(cssrRequisitions($pdo,['date'=>date('Y-m-d')],true,0)['total']===3,'Date filter');
check(cssrRequisitions($pdo,['date'=>'2026-02-31'],true,0)['filters']['date']==='','Invalid date ignored');
check(cssrRequisitions($pdo,['department'=>2],true,0)['total']===5,'Department filter');
$own=cssrRequisitions($pdo,[],false,2);
check($own['total']===5 && count($own['departments'])===1,'Department-scoped records and filters');
check(cssrRequisitions($pdo,['department'=>1,'view'=>1],false,2)['selected']===null,'Direct detail access cannot escape department');
check(cssrRequisitions($pdo,['view'=>1],false,0)['total']===0,'Unassigned department fails closed');
$detail=cssrRequisitions($pdo,['view'=>1],true,0);
check(count($detail['details'])===3,'Item details loaded');
check($detail['details'][0]['available_stock']===1080,'Available stock subtracts reservations');
check(cssrRequisitions($pdo,['view'=>2],true,0)['selected']['display_status']==='For Release','Valid reservations ready');
check(cssrRequisitions($pdo,['view'=>3],true,0)['selected']['display_status']==='Approved','Missing reservations remain Approved');
$pdo->exec("UPDATE stock_reservations SET expires_at='2000-01-01' WHERE request_id=2");
check(cssrRequisitions($pdo,['view'=>2],true,0)['selected']['display_status']==='Approved','Expired reservations not ready');
check(cssrRequisitions($pdo,['view'=>1],true,0)['details'][0]['available_stock']===1120,'Expired reservations no longer reduce free stock');
$pdo->exec("UPDATE stock_reservations SET expires_at='2099-01-01' WHERE request_id=2; UPDATE item_lots SET expiry_date='2000-01-01' WHERE id=1");
check(cssrRequisitions($pdo,['view'=>2],true,0)['selected']['display_status']==='Approved','Expired lot not releasable');
check(cssrRequisitions($pdo,['view'=>1],true,0)['details'][0]['available_stock']===0,'Expired stock excluded');
$pdo->exec("UPDATE item_lots SET expiry_date='2099-06-30',quantity_available=100 WHERE id=1");
check(cssrRequisitions($pdo,['status'=>'For Release'],true,0)['total']===0,'Overcommitted lots block all affected releases');
$pdo->exec("UPDATE item_lots SET quantity_available=1200 WHERE id=1; UPDATE stock_reservations SET quantity=1 WHERE request_detail_id=21");
check(cssrRequisitions($pdo,['view'=>2],true,0)['selected']['display_status']==='Approved','Reservation must cover approved quantity');
$pdo->exec("UPDATE stock_reservations SET quantity=40 WHERE request_detail_id=21; UPDATE item_request_details SET quantity_released=1 WHERE id=21");
check(cssrRequisitions($pdo,['view'=>2],true,0)['selected']['display_status']==='Approved','Already issued detail blocks repeated release');
$pdo->exec("UPDATE item_requests SET status='Deleted' WHERE id=1");
check(cssrRequisitions($pdo,['view'=>1],true,0)['selected']===null,'Deleted requests hidden');
check(cssrRequisitionBadge('For Approval')==='warning' && cssrRequisitionBadge('Rejected')==='danger','Status colors');
echo "Passed $checks requisition data checks. No hospital records changed.\n";
